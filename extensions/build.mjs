// An original arrow/tray mark, drawn at each output size without a graphics dependency.
function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const name = Buffer.from(type); const size = Buffer.alloc(4); size.writeUInt32BE(data.length);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(Buffer.concat([name, data])));
  return Buffer.concat([size, name, data, crc]);
}
function icon(size) {
  const rows = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const nx = (x + .5) / size, ny = (y + .5) / size;
    const cornerX = Math.max(.20 - nx, nx - .80, 0), cornerY = Math.max(.20 - ny, ny - .80, 0);
    const inside = cornerX * cornerX + cornerY * cornerY <= .18 * .18 && nx > .02 && nx < .98 && ny > .02 && ny < .98;
    const stem = nx > .455 && nx < .545 && ny > .22 && ny < .60;
    const arrow = ny > .43 && ny < .68 && Math.abs(nx - .5) < (.68 - ny) && Math.abs(nx - .5) > Math.max(0, .59 - ny);
    const tray = ny > .72 && ny < .79 && nx > .25 && nx < .75 || ny > .63 && ny < .76 && (nx > .25 && nx < .32 || nx > .68 && nx < .75);
    const white = stem || arrow || tray;
    const at = y * (size * 4 + 1) + 1 + x * 4;
    rows[at] = white ? 255 : 35; rows[at + 1] = white ? 255 : 98; rows[at + 2] = white ? 255 : 213; rows[at + 3] = inside ? 255 : 0;
  }
  const header = Buffer.alloc(13); header.writeUInt32BE(size, 0); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), chunk('IHDR', header), chunk('IDAT', deflateSync(rows)), chunk('IEND', Buffer.alloc(0))]);
}
